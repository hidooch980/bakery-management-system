import 'package:uuid/uuid.dart';

/// نام‌هایی برای نوشتن‌هایی که هنوز نگرفته‌اند.
///
/// یک timeout یعنی درخواست به سرور رسیده و به احتمال زیاد اجرا هم شده، و
/// فقط جوابش گم شده. صفحه خطا نشان می‌دهد و مالک دوباره می‌زند — و بدون
/// نام، سرور آن تلاش دوم را یک پرداخت تازه می‌بیند و از حساب دو بار کم
/// می‌کند.
///
/// نام به **قصد** گره می‌خورد، نه به فراخوانی: تا وقتی همان کار با همان
/// عددها دوباره تلاش می‌شود، همان نام می‌رود. به‌محض گرفتن، نام فراموش
/// می‌شود — کار بعدی، کار بعدی است.
///
/// و قصد باید مبلغ را هم در خود داشته باشد. اگر نام فقط به «این
/// کارخانه» گره می‌خورد، پرداخت شکست‌خورده‌ٔ ۱ میلیون و پرداخت بعدیِ ۲
/// میلیون یک نام می‌گرفتند، و سرور دومی را تکرار اولی می‌دید و اصلاً ثبت
/// نمی‌کرد. آن، خطای بدتری از دوباره‌نویسی است: پولی که داده شده و هیچ
/// ردیفی ندارد.
class OneWrite {
  final Map<String, String> _names = {};

  static const _uuid = Uuid();

  /// نام این قصد، ساخته در اولین بار و همان در هر تلاش بعدی.
  String nameFor(String intent) => _names[intent] ??= _uuid.v4();

  /// گرفت. نام دیگر لازم نیست.
  void done(String intent) => _names.remove(intent);

  /// چند قصد هنوز نامِ باز دارند. برای تست.
  int get open => _names.length;
}
