<?php

namespace App\Support;

/**
 * قاعدهٔ «این گوشی نسخهٔ تازه را می‌گیرد یا نه»، در یک جا.
 *
 * تا امروز این عدد فقط داخل AuthController بود، چون فقط یک صفحه
 * لازمش داشت. حالا صفحهٔ گوشی‌های کارکنان هم همان را می‌پرسد، و
 * نوشتنِ یک عدد در دو جا همان کاری است که این پروژه بارها بهایش را
 * داده: دو جا که روزی با هم اختلاف پیدا می‌کنند و هیچ‌کدام غلط به
 * نظر نمی‌رسد.
 */
final class Handsets
{
    /**
     * قدیمی‌ترین اندرویدی که یک APK منتشرشده رویش نصب می‌شود.
     *
     * همان `minSdk` در `mobile-app/android/app/build.gradle.kts`.
     * اینجا دوباره نوشته شده چون سرور است که باید جواب «چرا روی آن
     * گوشی نصب نمی‌شود» را بدهد.
     *
     * ‏۲۴ یعنی اندروید ۷.۰. در ماه‌های اول اپ ۲۳ و پیش از آن ۲۱ بود،
     * پس گوشیِ پایین‌تر از این ممکن است بیلدِ قدیمی را کاملاً سالم
     * اجرا کند: اندروید این را موقع نصب بررسی می‌کند، نه بعدش.
     */
    public const MIN_ANDROID_SDK = 24;

    /**
     * آیا این گوشی به‌روزرسانی می‌گیرد؟ و null یعنی نمی‌دانیم.
     *
     * «نمی‌دانیم» جوابِ خودش است نه یک جوابِ غلط: هشدار روی گوشی‌ای
     * که فقط چیزی گزارش نکرده، کسی را می‌فرستد گوشیِ سالم عوض کند.
     */
    public static function canInstallUpdates(?int $sdkInt): ?bool
    {
        return $sdkInt === null ? null : $sdkInt >= self::MIN_ANDROID_SDK;
    }
}
